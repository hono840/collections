/** 指定 id の FAQ を宣言順で抜き出す（ランディング/料金の抜粋用）。 */
export function pickFaq(ids: readonly string[]): FaqItem[] {
  return ids.map((id) => FAQ_ITEMS.find((item) => item.id === id)).filter((item): item is FaqItem => item !== undefined)
}

